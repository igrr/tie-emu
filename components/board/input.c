#include <stdatomic.h>
#include "input.h"

#define QLEN 256

static input_event_t s_q[QLEN];
static atomic_uint s_head, s_tail;

bool input_push(const input_event_t *ev)
{
    unsigned t = atomic_load_explicit(&s_tail, memory_order_relaxed);
    if (t - atomic_load_explicit(&s_head, memory_order_acquire) >= QLEN) {
        return false;
    }
    s_q[t % QLEN] = *ev;
    atomic_store_explicit(&s_tail, t + 1, memory_order_release);
    return true;
}

