void input_drain(machine_t *m)
{
    unsigned h = atomic_load_explicit(&s_head, memory_order_relaxed);
    unsigned t = atomic_load_explicit(&s_tail, memory_order_acquire);
    for (; h != t; h++) {
        const input_event_t *ev = &s_q[h % QLEN];
        if (ev->type == INPUT_KEY) {
            uint16_t sc = ev->code < 256 ? s_hid_to_set1[ev->code] : 0;
            if (!sc) {
                continue;
            }
            if (sc >> 8) {
                machine_key(m, 0xe0);
            }
            machine_key(m, (uint8_t)(sc & 0x7f) | (ev->down ? 0 : 0x80));
        } else {
            machine_mouse(m, ev->dx, ev->dy, ev->buttons);
        }
    }
    atomic_store_explicit(&s_head, h, memory_order_release);
}
